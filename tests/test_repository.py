"""Raw bytes and index invariants are separate from Git's cached status."""

import os
from unittest.mock import patch

from helper_support import GitFixture, cwd, source
import repository


class RepositoryTests(GitFixture):
    def verify(self, **kwargs):
        with cwd(self.local), patch.dict(os.environ, self.env, clear=True):
            repository.verify_checkout(self.sha, **kwargs)

    def test_selected_clean_raw_checkout_and_immutable_head(self):
        self.verify()
        self.git("commit", "--quiet", "--allow-empty", "-m", "changed HEAD")
        with self.assertRaisesRegex(ValueError, "HEAD"):
            self.verify()

    def test_reversed_staging_cannot_hide_index_source_drift(self):
        path = self.local / source.PROJECT
        before = path.read_bytes()
        path.write_bytes(before + b"\n")
        self.git("add", "--", str(source.PROJECT))
        path.write_bytes(before)
        with self.assertRaisesRegex(ValueError, "Index"):
            self.verify(final=True)

    def test_hidden_flags_fail_even_when_bytes_match(self):
        for flag in ("--assume-unchanged", "--skip-worktree"):
            self.git("update-index", flag, "--", str(source.PLIST))
            with self.assertRaisesRegex(ValueError, "index flags"):
                self.verify(final=True)
            self.git("update-index", "--no-" + flag[2:], "--", str(source.PLIST))

    def test_raw_byte_and_executable_mode_drift_fail(self):
        path = self.local / source.PLIST
        before = path.read_bytes()
        path.write_bytes(before + b" ")
        with self.assertRaisesRegex(ValueError, "Working"):
            self.verify(final=True)
        path.write_bytes(before)
        path.chmod(0o755)
        with self.assertRaisesRegex(ValueError, "Working"):
            self.verify(final=True)

    def test_ignored_untracked_source_is_checked_without_status_exclude_rules(self):
        (self.local / ".gitignore").write_text("build/\n")
        self.git("add", ".gitignore")
        self.git("commit", "--quiet", "-m", "ignore fixture")
        self.sha = self.git("rev-parse", "HEAD")
        path = self.local / "build/unexpected-source.cpp"
        path.parent.mkdir()
        path.write_text("unreviewed")
        self.assertEqual(self.git("status", "--porcelain"), "")
        for final in (False, True):
            with self.assertRaisesRegex(ValueError, "Untracked"):
                self.verify(final=final)

    def test_final_preserves_generated_worktree_bytes_but_not_staged_generated_changes(self):
        path = self.local / "generated.plist"
        path.write_bytes(b"selected generated bytes")
        self.git("add", "generated.plist")
        self.git("commit", "--quiet", "-m", "generated fixture")
        self.sha = self.git("rev-parse", "HEAD")
        output = b"fresh generated bytes\0retained"
        path.write_bytes(output)
        generated = lambda value: value == "generated.plist"
        self.verify(final=True, generated=generated)
        self.assertEqual(path.read_bytes(), output)
        self.git("add", "generated.plist")
        with self.assertRaisesRegex(ValueError, "Index"):
            self.verify(final=True, generated=generated)

    def test_symlink_ancestor_cannot_redirect_source(self):
        source_dir = self.local / source.PROJECT.parent
        moved = self.root / "redirected-project"
        source_dir.rename(moved)
        source_dir.symlink_to(moved, target_is_directory=True)
        with self.assertRaisesRegex(ValueError, "symlink ancestor"):
            self.verify(final=True)

    def test_final_generated_symlink_leaf_or_ancestor_rejected(self):
        path = self.local / "generated/output"
        path.parent.mkdir()
        path.write_bytes(b"selected generated bytes")
        self.git("add", "generated/output")
        self.git("commit", "--quiet", "-m", "generated fixture")
        self.sha = self.git("rev-parse", "HEAD")
        target = self.root / "redirected-output"
        target.write_bytes(b"fresh output")
        generated = lambda value: value.startswith("generated/")
        path.unlink()
        path.symlink_to(target)
        with self.assertRaisesRegex(ValueError, "regular nonsymlink"):
            self.verify(final=True, generated=generated)
        path.unlink()
        path.write_bytes(b"fresh output")
        moved = self.root / "redirected-directory"
        path.parent.rename(moved)
        path.parent.symlink_to(moved, target_is_directory=True)
        with self.assertRaisesRegex(ValueError, "regular nonsymlink"):
            self.verify(final=True, generated=generated)

    def test_final_untracked_generated_symlink_rejected(self):
        output = self.local / "generated-output"
        output.symlink_to(self.local / source.PLIST)
        with self.assertRaisesRegex(ValueError, "regular nonsymlink"):
            self.verify(final=True, generated=lambda path: path == "generated-output")
